-- | Resolve a canonical or alias mechanism name to its id.
generatedIdByName :: Text -> Maybe Word64
generatedIdByName name =
  case lookup name [(n, w) | (w, n, _) <- generatedInventory] of
    Just w -> Just w
    Nothing ->
      lookup name [(a, w) | (w, _, als) <- generatedInventory, a <- als]

-- | Resolve a generated id by name. PARTIAL: calls 'error' on unknown text;
-- static call sites use the generated 'ckm_*' constants instead,
-- dynamic lookup stays explicitly fallible via 'generatedIdByName'.
mustGeneratedId :: Text -> Word64
mustGeneratedId name = case generatedIdByName name of
  Just w -> w
  Nothing -> error ("mustGeneratedId: unknown " ++ show name)

