#!/usr/bin/env python3
"""Generate the single-authority return values from the spec name list.

Reads:
  spec/return-codes.json            served CK_RV names, append-only
  spec/vendor/pkcs11.h              numeric authority (#defines)

Writes (deterministic bytes, no timestamps):
  core/Haskoki/ReturnCode/Generated.hs   the ReturnCode type + returnCodeToRV
  cbits/rv_served.inc                    static asserts pinning served values

STDLIB ONLY. Run on HOST python3 from anywhere:
  python3 scripts/generate-return-codes.py [OUT-HS OUT-INC]
(without args, writes the committed paths; with args, the test paths).

A served code missing from the locked headers fails loudly: numerics
are never invented here.
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SPEC = REPO / "spec" / "return-codes.json"
HDR = REPO / "spec" / "vendor" / "pkcs11.h"
HS_OUT = REPO / "core" / "Haskoki" / "ReturnCode" / "Generated.hs"
C_OUT = REPO / "cbits" / "rv_served.inc"


def fail(msg):
    print(f"generate-return-codes: FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def main(hs_out=None, c_out=None):
    try:
        spec = json.loads(SPEC.read_text())
    except Exception as e:  # noqa: BLE001 - reported, not hidden
        fail(f"cannot parse {SPEC}: {e}")
    codes = spec.get("codes")
    if not isinstance(codes, list) or not codes or \
            len(set(codes)) != len(codes) or \
            not all(re.fullmatch(r"CKR_[A-Z0-9_]+", c) for c in codes):
        fail("spec codes is not a unique non-empty CKR_ list")
    defs = dict(re.findall(r"#define\s+(CKR_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+)UL",
                           HDR.read_text()))
    missing = [c for c in codes if c not in defs]
    if missing:
        fail(f"codes missing from locked headers: {missing}")
    hs_lines = [
        "-- GENERATED by scripts/generate-return-codes.py - DO NOT EDIT.",
        "-- Single authority: spec/return-codes.json names + locked",
        "-- header numerics. Append-only; a removal needs an ADR.",
        "module Haskoki.ReturnCode.Generated",
        "  ( ReturnCode (..)",
        "  , returnCodeToRV",
        "  ) where",
        "",
        "import Data.Word (Word32)",
        "",
        "data ReturnCode",
        "  = " + "\n  | ".join(codes),
        "  deriving (Eq, Show)",
        "",
        "returnCodeToRV :: ReturnCode -> Word32",
        "returnCodeToRV code = case code of",
    ]
    hs_lines += ["  %s -> %s" % (c, defs[c]) for c in codes]
    c_lines = [
        "/* GENERATED by scripts/generate-return-codes.py - DO NOT EDIT.",
        " * Served-set parity pins: compilation fails if a served value",
        " * drifts from spec/vendor/pkcs11.h. Included once, from",
        " * cbits/exports.c next to abi_generated.h (function_tables.c",
        " * keeps its local cryptoki subset and must not see vendor",
        " * headers). */",
        '#include "pkcs11.h"',
        "",
    ]
    c_lines += ["_Static_assert(%s == %sUL, \"rv_served %s\");"
                % (c, defs[c], c) for c in codes]
    (hs_out or HS_OUT).parent.mkdir(parents=True, exist_ok=True)
    (hs_out or HS_OUT).write_text("\n".join(hs_lines) + "\n")
    (c_out or C_OUT).write_text("\n".join(c_lines) + "\n")
    print(f"generate-return-codes: {len(codes)} codes "
          f"(+{len(codes) - 48} over the hand type)")
    return 0


if __name__ == "__main__":
    if len(sys.argv) not in (1, 3):
        print("usage: generate-return-codes.py [HS-OUT C-OUT]",
              file=sys.stderr)
        sys.exit(2)
    if len(sys.argv) == 3:
        sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
    sys.exit(main())
