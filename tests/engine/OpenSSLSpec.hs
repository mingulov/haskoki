    cipherEncrypt env C_AES128_CTS (KeyBytes cts128Key64) "short" cts128Pt64
  -- CS1 degenerates to plain CBC at exactly one block: cross-check.
  oneBlock <- expectOk "cts 1-block encrypt" =<<
