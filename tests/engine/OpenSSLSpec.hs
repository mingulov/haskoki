    cipherEncrypt env C_AES256_CBC (KeyBytes aes256Key) aes256Iv aes256Pt
  assertEqual "cts==cbc at 16 bytes" oneBlockCbc oneBlock
  where
    katCts env label cipher key iv pt want = do
