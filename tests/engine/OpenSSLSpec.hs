    cipherDecrypt env C_AES128_CTS (KeyBytes cts128Key64) cts128Iv64 "short!!"
  expectBadParam "cts bad key length" =<<
    cipherEncrypt env C_AES128_CTS (KeyBytes "short") cts128Iv64 cts128Pt64
